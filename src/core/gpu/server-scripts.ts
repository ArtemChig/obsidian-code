// Server-side scripts for the rented instance (owner: gpu).
// resources/server/onstart.sh  → Vast `onstart` (small stub: arms the self-destroy watchdog FIRST, then unpacks
//                                 bootstrap.sh + config.sh from env vars and starts the bootstrap)
// resources/server/bootstrap.sh → shipped gzip+base64 in env OC_BOOTSTRAP_GZB64 (fallback: uploaded over SSH)
// config.sh (rendered here)     → catalog table (repo/files/args per model) + extra llama args, env OC_CONFIG_GZB64
//
// Resources are resolved from OBSIDIAN_RESOURCES_DIR, else <cwd>/resources (never __dirname: bundled by electron-vite).

import { existsSync, readFileSync } from 'node:fs';
import path from 'node:path';
import { gzipSync } from 'node:zlib';
import type { CatalogModel, GpuServerMode } from '../../shared/types';

/** Vast's documented onstart limit is ~4048 chars; stay safely below. */
export const ONSTART_MAX_CHARS = 4000;

export interface ServerScripts {
  onstart: string;
  bootstrap: string;
}

export function resolveResourcesDir(override?: string): string {
  if (override) return override;
  const env = process.env.OBSIDIAN_RESOURCES_DIR;
  if (env) return env;
  return path.join(process.cwd(), 'resources');
}

/** Normalise to LF (git on Windows may check the scripts out with CRLF, which breaks bash). */
export function toLf(s: string): string {
  return s.replace(/\r\n?/g, '\n');
}

/** Drop full-line comments (keeps shebangs / "#!" lines) and blank lines to keep the onstart stub small. */
export function compactShell(s: string): string {
  return toLf(s)
    .split('\n')
    .filter((line) => !/^\s*#(\s|$)/.test(line) && line.trim() !== '')
    .join('\n') + '\n';
}

export function loadServerScripts(resourcesDir?: string): ServerScripts {
  const dir = path.join(resolveResourcesDir(resourcesDir), 'server');
  const onPath = path.join(dir, 'onstart.sh');
  const bsPath = path.join(dir, 'bootstrap.sh');
  if (!existsSync(onPath) || !existsSync(bsPath)) {
    throw new Error(`GPU server scripts not found in ${dir} (set OBSIDIAN_RESOURCES_DIR). Nothing was rented.`);
  }
  const onstart = compactShell(readFileSync(onPath, 'utf8'));
  const bootstrap = toLf(readFileSync(bsPath, 'utf8'));
  if (onstart.length >= ONSTART_MAX_CHARS) {
    throw new Error(`onstart stub is ${onstart.length} chars (limit ${ONSTART_MAX_CHARS}). Nothing was rented.`);
  }
  return { onstart, bootstrap };
}

/** POSIX single-quote a string for bash. */
export function shQuote(s: string): string {
  return `'${String(s).replace(/'/g, `'\\''`)}'`;
}

function shArray(items: string[]): string {
  return `(${items.map(shQuote).join(' ')})`;
}

/** config.sh: `oc_model <id>` sets M_FAMILY M_REPO M_FILES M_MMPROJ M_BYTES M_CTX M_ARGS; OC_EXTRA = extra llama args. */
export function renderConfigSh(models: readonly CatalogModel[], extraArgs: readonly string[] = [], opts: { loadMaxMin?: number } = {}): string {
  const lines: string[] = [
    '# Generated by Obsidian Code (src/core/gpu/server-scripts.ts). Do not edit on the instance.',
    `OC_EXTRA=${shArray([...extraArgs])}`,
    `LOAD_MAX_MIN=${Math.max(1, Math.round(opts.loadMaxMin ?? 25))}`,
    'oc_model() {',
    "  M_FAMILY=''; M_REPO=''; M_FILES=(); M_MMPROJ=''; M_BYTES=0; M_CTX=32768; M_ARGS=()",
    '  case "$1" in',
  ];
  for (const m of models) {
    const bytes = Math.round(m.sizeGb * 1e9);
    lines.push(
      `    ${shQuote(m.id)}) M_FAMILY=${shQuote(m.family)}; M_REPO=${shQuote(m.repo)}; M_FILES=${shArray(m.files)}; ` +
        `M_MMPROJ=${shQuote(m.mmproj ?? '')}; M_BYTES=${bytes}; M_CTX=${Math.round(m.contextLength)}; M_ARGS=${shArray(m.llamaArgs)} ;;`,
    );
  }
  lines.push('    *) return 1 ;;', '  esac', '  return 0', '}', '');
  return lines.join('\n');
}

export function gzipBase64(s: string): string {
  return gzipSync(Buffer.from(s, 'utf8'), { level: 9 }).toString('base64');
}

export interface InstanceEnvParams {
  modelId: string;
  apiKey: string;
  idleMinutes: number;
  heartbeatMinutes: number;
  maxSessionHours: number;
  bootMaxMinutes: number;
  nonce: string;
  bootstrap: string;
  configSh: string;
}

/** Env dict for PUT /asks/{id}/ (`env` is a JSON object; vast-api.md §3.1). */
export function buildInstanceEnv(p: InstanceEnvParams): Record<string, string> {
  return {
    OC_MODEL_ID: p.modelId,
    OC_API_KEY: p.apiKey,
    OC_IDLE_MIN: String(Math.max(5, Math.round(p.idleMinutes))),
    OC_HEARTBEAT_MIN: String(Math.max(3, Math.round(p.heartbeatMinutes))),
    OC_MAX_HOURS: String(Math.max(1, Math.ceil(p.maxSessionHours))),
    OC_BOOT_MAX_MIN: String(Math.max(15, Math.round(p.bootMaxMinutes))),
    OC_NONCE: p.nonce,
    OC_BOOTSTRAP_GZB64: gzipBase64(p.bootstrap),
    OC_CONFIG_GZB64: gzipBase64(p.configSh),
  };
}

/** Boot deadline for the server watchdog: generous download time for the model (≥ 50 MB/s) + 30 min. */
export function bootMaxMinutesFor(m: Pick<CatalogModel, 'sizeGb'>): number {
  return Math.ceil(30 + (m.sizeGb * 1000) / 50 / 60);
}

/** Parse /root/oc/status.json written by bootstrap.sh. */
export interface ServerStatus {
  phase: 'starting' | 'downloading' | 'loading' | 'ready' | 'switching' | 'error' | string;
  progress: number;
  message: string;
  modelId: string;
  bytesDone: number;
  bytesTotal: number;
  updatedAt?: number;
  /** Load configuration (bootstrap.sh fallback): full → safe → safe-minimal. Present once loading started. */
  mode?: GpuServerMode;
  /** Features the fallback dropped: mtp, vision, flash-attn, kv-quant. */
  dropped?: string[];
  /** Load attempt (1-based) of the current serve. */
  attempt?: number;
  /** -c the server was started with. */
  ctx?: number;
}

const SERVER_MODES: readonly GpuServerMode[] = ['full', 'safe', 'safe-minimal'];

export function parseServerStatus(text: string): ServerStatus | null {
  try {
    const j = JSON.parse(text.trim()) as Partial<ServerStatus>;
    if (!j || typeof j !== 'object' || typeof j.phase !== 'string') return null;
    const st: ServerStatus = {
      phase: j.phase,
      progress: Number.isFinite(Number(j.progress)) ? Number(j.progress) : 0,
      message: typeof j.message === 'string' ? j.message : '',
      modelId: typeof j.modelId === 'string' ? j.modelId : '',
      bytesDone: Number(j.bytesDone) || 0,
      bytesTotal: Number(j.bytesTotal) || 0,
      updatedAt: typeof j.updatedAt === 'number' ? j.updatedAt : undefined,
    };
    if (typeof j.mode === 'string' && SERVER_MODES.includes(j.mode)) st.mode = j.mode;
    if (Array.isArray(j.dropped)) st.dropped = j.dropped.filter((d): d is string => typeof d === 'string');
    if (Number.isFinite(Number(j.attempt)) && Number(j.attempt) > 0) st.attempt = Number(j.attempt);
    if (Number.isFinite(Number(j.ctx)) && Number(j.ctx) > 0) st.ctx = Number(j.ctx);
    return st;
  } catch {
    return null;
  }
}

/** Parse /root/oc/env (`export K='v'` lines). */
export function parseEnvFile(text: string): Record<string, string> {
  const out: Record<string, string> = {};
  for (const line of toLf(text).split('\n')) {
    const m = /^export\s+([A-Z0-9_]+)='([^']*)'\s*$/.exec(line.trim());
    if (m) out[m[1]] = m[2];
  }
  return out;
}
